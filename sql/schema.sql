-- Run once in Supabase SQL Editor. All data is accessed through authorized Next.js API routes.
-- No RLS policy for anon/authenticated: clients cannot directly query member records.
create extension if not exists pgcrypto;

create table if not exists public.organizers (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text,
  created_at timestamptz not null default now()
);
create table if not exists public.events (
  id uuid primary key default gen_random_uuid(),
  organizer_id uuid not null references public.organizers(id) on delete cascade,
  name text not null check(char_length(name) between 2 and 120),
  slug text not null unique check(slug ~ '^[a-z0-9-]{3,90}$'),
  timezone text not null default 'Asia/Kolkata',
  is_published boolean not null default true,
  created_at timestamptz not null default now()
);
create index if not exists events_organizer_idx on public.events(organizer_id);

create table if not exists public.event_members (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  mobile text not null check(mobile ~ '^[6-9][0-9]{9}$'),
  access_hash text not null,
  qr_token text not null unique,
  first_name text not null default '',
  father_name text not null default '',
  surname text not null default '',
  pincode text not null default '',
  village text not null default '',
  taluka text not null default '',
  district text not null default '',
  address text not null default '',
  extra_data jsonb not null default '{}'::jsonb,
  profile_confirmed boolean not null default false,
  confirmed_at timestamptz,
  session_version int not null default 1,
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(event_id,mobile)
);
create index if not exists event_members_event_idx on public.event_members(event_id);

create table if not exists public.meetings (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  meeting_number int not null check(meeting_number between 1 and 3),
  title text not null,
  meeting_date date,
  is_open boolean not null default false,
  is_completed boolean not null default false,
  created_at timestamptz not null default now(),
  unique(event_id,meeting_number)
);
create index if not exists meetings_event_idx on public.meetings(event_id);

create table if not exists public.attendance (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  meeting_id uuid not null references public.meetings(id) on delete cascade,
  member_id uuid not null references public.event_members(id) on delete cascade,
  scanned_by uuid not null references public.organizers(id),
  scanned_at timestamptz not null default now(),
  unique(meeting_id,member_id)
);
create index if not exists attendance_event_idx on public.attendance(event_id);
create index if not exists attendance_member_idx on public.attendance(member_id);

-- Enforces that meeting, member and attendance event IDs agree even if API code has a bug.
create or replace function public.check_attendance_same_event()
returns trigger language plpgsql as $$
begin
  if not exists(select 1 from public.meetings where id = new.meeting_id and event_id = new.event_id)
     or not exists(select 1 from public.event_members where id = new.member_id and event_id = new.event_id) then
    raise exception 'Meeting/member does not belong to the event';
  end if;
  return new;
end;
$$;
drop trigger if exists attendance_same_event on public.attendance;
create trigger attendance_same_event before insert or update on public.attendance
for each row execute function public.check_attendance_same_event();

create table if not exists public.import_batches (
  id uuid primary key default gen_random_uuid(),
  event_id uuid not null references public.events(id) on delete cascade,
  filename text not null,
  headers jsonb not null default '[]'::jsonb,
  mapping jsonb not null default '{}'::jsonb,
  total_rows int not null default 0,
  processed_rows int not null default 0,
  created_rows int not null default 0,
  skipped_rows int not null default 0,
  created_at timestamptz not null default now()
);
create index if not exists import_batches_event_idx on public.import_batches(event_id);

-- Records login attempts for temporary-code brute force protection.
create table if not exists public.member_login_attempts (
  id bigint generated by default as identity primary key,
  event_id uuid not null references public.events(id) on delete cascade,
  mobile text not null,
  ip_hash text not null,
  attempted_at timestamptz not null default now()
);
create index if not exists attempts_mobile_idx on public.member_login_attempts(event_id,mobile,attempted_at desc);
create index if not exists attempts_ip_idx on public.member_login_attempts(ip_hash,attempted_at desc);

-- Simple atomic limiter: inserts the attempt inside the same transaction as counting;
-- uses an advisory transaction lock for the event/mobile key to prevent concurrent bypasses.
create or replace function public.reserve_member_login_attempt(p_event_id uuid, p_mobile text, p_ip_hash text)
returns boolean
language plpgsql security definer set search_path = public, pg_temp as $$
declare mobile_count bigint; ip_count bigint;
begin
  perform pg_advisory_xact_lock(hashtextextended(p_event_id::text || ':' || p_mobile, 0));
  select count(*) into mobile_count from public.member_login_attempts
    where event_id = p_event_id and mobile = p_mobile and attempted_at >= now() - interval '15 minutes';
  select count(*) into ip_count from public.member_login_attempts
    where ip_hash = p_ip_hash and attempted_at >= now() - interval '15 minutes';
  if mobile_count >= 8 or ip_count >= 20000 then return false; end if;
  insert into public.member_login_attempts(event_id,mobile,ip_hash) values(p_event_id,p_mobile,p_ip_hash);
  return true;
end;
$$;
revoke all on function public.reserve_member_login_attempt(uuid,text,text) from public, anon, authenticated;
grant execute on function public.reserve_member_login_attempt(uuid,text,text) to service_role;

