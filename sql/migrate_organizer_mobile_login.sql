-- Existing installations: run after schema.sql in Supabase SQL Editor.
-- Adds mobile login support without changing organizer accounts or passwords.
begin;

alter table public.organizers add column if not exists mobile text;
alter table public.organizers add column if not exists password_hash text;
create unique index if not exists organizers_mobile_idx
  on public.organizers(mobile) where mobile is not null;

create table if not exists public.organizer_login_attempts (
  id bigint generated by default as identity primary key,
  mobile text not null,
  ip_hash text not null,
  attempted_at timestamptz not null default now()
);
create index if not exists organizer_attempts_mobile_idx
  on public.organizer_login_attempts(mobile, attempted_at desc);
create index if not exists organizer_attempts_ip_idx
  on public.organizer_login_attempts(ip_hash, attempted_at desc);

create or replace function public.reserve_organizer_login_attempt(p_mobile text, p_ip_hash text)
returns boolean
language plpgsql security definer set search_path = public, pg_temp as $$
declare mobile_count bigint; ip_count bigint;
begin
  perform pg_advisory_xact_lock(hashtextextended('organizer:mobile:' || p_mobile, 0));
  perform pg_advisory_xact_lock(hashtextextended('organizer:ip:' || p_ip_hash, 0));
  select count(*) into mobile_count from public.organizer_login_attempts
    where mobile = p_mobile and attempted_at >= now() - interval '15 minutes';
  select count(*) into ip_count from public.organizer_login_attempts
    where ip_hash = p_ip_hash and attempted_at >= now() - interval '15 minutes';
  if mobile_count >= 8 or ip_count >= 1000 then return false; end if;
  insert into public.organizer_login_attempts(mobile, ip_hash) values (p_mobile, p_ip_hash);
  return true;
end;
$$;

alter table public.organizer_login_attempts enable row level security;
revoke all on function public.reserve_organizer_login_attempt(text,text) from public, anon, authenticated;
grant usage on schema public to service_role;
grant select, insert, update, delete on table public.organizers, public.organizer_login_attempts to service_role;
grant usage, select on sequence public.organizer_login_attempts_id_seq to service_role;
grant execute on function public.reserve_organizer_login_attempt(text,text) to service_role;

commit;
